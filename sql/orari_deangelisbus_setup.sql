create table if not exists orari_linee (
  id text primary key,
  nome text not null,
  nome_itineris text,
  colore text,
  ordine int default 0,
  attiva boolean default true,
  note text
);

create table if not exists orari_fermate (
  id int primary key,
  nome text not null,
  comune text not null,
  frazione text,
  descrizione text,
  codice_contabile text,
  zona_tariffaria text,
  lat double precision not null,
  lon double precision not null
);

create table if not exists orari_percorsi (
  id text primary key,
  linea_id text not null references orari_linee(id) on delete cascade,
  direzione char(1) not null check (direzione in ('A','R')),
  nome text not null
);

-- sequenza fermate di ogni percorso; minuti = minuti dopo la partenza dal capolinea
create table if not exists orari_percorsi_fermate (
  percorso_id text not null references orari_percorsi(id) on delete cascade,
  ordine int not null,
  fermata_id int not null references orari_fermate(id),
  minuti int,                 -- tempo confermato
  minuti_stimati int,         -- stima da km polimetrica (50 km/h), usata finche' minuti e' vuoto
  primary key (percorso_id, ordine)
);

create table if not exists orari_corse (
  codice text primary key,
  linea_id text not null references orari_linee(id) on delete cascade,
  percorso_id text not null references orari_percorsi(id),
  denominazione text,
  direzione char(1) not null check (direzione in ('A','R')),
  partenza time not null,
  frequenza text,
  giorni smallint[] not null,          -- 1=lun ... 7=dom
  stagionale text,                     -- es. 'agricola' (null = tutto l'anno)
  attiva boolean default true
);

-- tariffe da polimetrica Itineris (simmetriche: vale anche a->da)
create table if not exists orari_tariffe (
  linea_id text not null references orari_linee(id) on delete cascade,
  tipo_codice int not null,
  tipo_nome text not null,
  da_zona text not null,
  a_zona text not null,
  km numeric,
  prezzo numeric(6,2) not null,
  prezzo_scontato numeric(6,2),
  primary key (linea_id, tipo_codice, da_zona, a_zona)
);

-- avvisi (scioperi, variazioni) mostrati in app
create table if not exists orari_avvisi (
  id bigint generated always as identity primary key,
  titolo text not null,
  testo text,
  linea_id text references orari_linee(id) on delete cascade,
  dal date default current_date,
  al date,
  creato_il timestamptz default now()
);

-- vista comoda: orario di passaggio di ogni corsa a ogni fermata
create or replace view orari_passaggi with (security_invoker = true) as
select c.codice as corsa, c.linea_id, c.direzione, c.giorni, c.stagionale, c.attiva,
       pf.ordine, f.id as fermata_id, f.nome as fermata, f.comune, f.lat, f.lon,
       (c.partenza + make_interval(mins => coalesce(pf.minuti, pf.minuti_stimati, 0)))::time as orario,
       (pf.minuti is not null or pf.ordine = 1) as orario_confermato,
       f.zona_tariffaria
from orari_corse c
join orari_percorsi_fermate pf on pf.percorso_id = c.percorso_id
join orari_fermate f on f.id = pf.fermata_id;

-- lettura pubblica (app senza login). Nessuna policy di scrittura: per ora si modifica
-- dal pannello Supabase; col modulo Orari del gestionale aggiungeremo la scrittura per i soli admin
do $$
declare t text;
begin
  foreach t in array array['orari_linee','orari_fermate','orari_percorsi','orari_percorsi_fermate','orari_corse','orari_avvisi','orari_tariffe'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "lettura pubblica" on %I', t);
    execute format('create policy "lettura pubblica" on %I for select to anon, authenticated using (true)', t);
  end loop;
end $$;
grant select on orari_passaggi to anon, authenticated;

